'use strict';

// Builds preview/assets/search-index.js, the list of pages the design system search looks through.
// Each page gets its title, address, a description (the page's intro, or its first paragraph),
// its headings and the start of its text. Run with: npm run build:search

const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');

const ROOT = path.join(__dirname, '..');
const PREVIEW = path.join(ROOT, 'preview');
const OUTPUT = path.join(PREVIEW, 'assets', 'search-index.js');

const SKIP_DIRS = new Set(['_includes', '_layouts', '_data', '_site', '_site_test', '.jekyll-cache', 'dist', 'assets', 'examples', 'testing', 'workshop', 'node_modules']);
const SKIP_LAYOUTS = new Set(['example', 'workshop']);
const SKIP_FILES = new Set(['search.html']);
const BODY_LIMIT = 4000;

// The section of the site a page belongs to, from its folder or, for a section's own landing page, its name.
const CATEGORIES = {
  components: 'Components',
  styles: 'Styles',
  patterns: 'Patterns',
  'get-started': 'Start prototyping',
  'content-guide': 'Content guide',
};

function categoryFor(address) {
  const parts = address.replace(/\.html$/, '').split('/');
  return CATEGORIES[parts[0]] || '';
}
const DESCRIPTION_LIMIT = 300;

const ENTITIES = { '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'", '&apos;': "'", '&nbsp;': ' ', '&ndash;': '–', '&mdash;': '—', '&rsquo;': '’', '&lsquo;': '‘', '&ldquo;': '“', '&rdquo;': '”' };

function decode(text) {
  return text
    .replace(/&#(\d+);/g, (m, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (m, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&[a-z]+;/gi, (m) => (m in ENTITIES ? ENTITIES[m] : m));
}

function toText(html) {
  return decode(html.replace(/<[^>]*>/g, ' ')).replace(/\s+/g, ' ').trim();
}

function parseFrontMatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return { data: {}, content: raw };
  return { data: yaml.load(match[1]) || {}, content: raw.slice(match[0].length) };
}

function stripTemplating(content) {
  return content
    .replace(/\{%-?\s*capture[\s\S]*?\{%-?\s*endcapture\s*-?%\}/g, ' ')
    .replace(/\{%-?\s*raw\s*-?%\}[\s\S]*?\{%-?\s*endraw\s*-?%\}/g, ' ')
    .replace(/\{%[\s\S]*?%\}/g, ' ')
    .replace(/\{\{[\s\S]*?\}\}/g, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<(script|style|pre|template|svg)\b[\s\S]*?<\/\1>/gi, ' ');
}

function trimToWords(text, limit) {
  if (text.length <= limit) return text;
  const cut = text.slice(0, limit);
  return cut.slice(0, cut.lastIndexOf(' ')).replace(/[,;:\s]+$/, '') + '…';
}

function findPages(dir, results = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) findPages(path.join(dir, entry.name), results);
    } else if (entry.name.endsWith('.html') && !SKIP_FILES.has(entry.name)) {
      results.push(path.join(dir, entry.name));
    }
  }
  return results;
}

function buildIndex() {
  const entries = [];
  for (const file of findPages(PREVIEW).sort()) {
    const { data, content } = parseFrontMatter(fs.readFileSync(file, 'utf8'));
    if (data.search_exclude || SKIP_LAYOUTS.has(data.layout)) continue;
    const html = stripTemplating(content);
    const headings = [...html.matchAll(/<h([1-3])\b[^>]*>([\s\S]*?)<\/h\1>/gi)].map((m) => toText(m[2])).filter(Boolean);
    const title = data.title ? String(data.title) : headings[0];
    if (!title) continue;
    let description = data.intro ? toText(String(data.intro)) : '';
    if (!description) {
      const paragraph = [...html.matchAll(/<p\b[^>]*>([\s\S]*?)<\/p>/gi)].map((m) => toText(m[1])).find((text) => text && !/^Updated in/i.test(text));
      description = paragraph || '';
    }
    const body = toText(html).slice(0, BODY_LIMIT);
    const address = path.relative(PREVIEW, file).split(path.sep).join('/');
    entries.push({
      t: title,
      u: address,
      c: categoryFor(address),
      d: trimToWords(description, DESCRIPTION_LIMIT),
      h: headings.filter((h) => h !== title),
      b: body,
    });
  }
  return entries;
}

function render(entries) {
  const lines = entries.map((e) => '  ' + JSON.stringify(e));
  return '// Generated by scripts/build-search-index.js. Run "npm run build:search" to refresh it.\nwindow.NHSW_SEARCH_INDEX = [\n' + lines.join(',\n') + '\n];\n';
}

function writeIndex() {
  const entries = buildIndex();
  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, render(entries));
  return entries;
}

if (require.main === module) {
  const entries = writeIndex();
  console.log('Indexed ' + entries.length + ' pages to ' + path.relative(ROOT, OUTPUT));
}

module.exports = { buildIndex, render, toText, writeIndex, CATEGORIES };
